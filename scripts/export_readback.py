"""Export read-back verifier: compare the artifacts on disk with what the deal's record regenerates (issue #196).

`deal_export.py` writes a deal's CAM `.docx` and spreading `.xlsx`; afterwards anybody can open and edit them. This
module regenerates the expected artifacts into a temporary directory -- the workbook from the deal's `state.json`
through the same input selection `export_deal()` uses, the document from the approved Markdown draft the deal
records -- and compares them with the files in the deal's dated folder, cell by cell and block by block. It is a
change detector for edits after export and for stale exports. It is NOT proof that the exporter is right: the
expected artifacts come from the same builders, so a systematic builder defect reproduces itself (the unit and
golden-snapshot tests are what guard the builders). It never parses CAM prose to test figures and never replaces
`policy_check.py` or `/review`.

Read-only for the deal: the only files it writes are temporary comparison artifacts, removed on exit. No
`anthropic` dependency. Exit status: 0 the artifacts match, 1 a mismatch (JSON findings on stdout) or an unusable
state/artifact/draft (one `error:` line on stderr), 2 a usage error.
"""
import hashlib
import json
import math
import os
import sys
import tempfile
from pathlib import PurePosixPath, PureWindowsPath

import docx
import openpyxl
from docx.table import Table
from docx.text.hyperlink import Hyperlink
from docx.text.paragraph import Paragraph

from deal_export import STATE_KEYS_READ, workbook_inputs_from_state
from docx_builder import export_to_docx
from spreading_builder import export_to_xlsx
from state_manager import (
    StateError, find_deal, read_state, sanitize_path_component, state_path, validate_iso_date_str, validate_state,
)

MAX_FINDINGS = 200
NUMERIC_TOLERANCE = 1e-9
# A real export is a few hundred rows by about a dozen columns. A sheet whose used range is far larger was edited
# (one cell in the far corner of a sheet makes the used range 1,048,576 rows by 16,384 columns), and comparing every
# position in it would run for hours: refuse it instead.
MAX_COMPARED_CELLS = 1_000_000

LIMITS = (
    "The expected files are regenerated by the same builders that wrote the originals, so this detects edits and "
    "stale exports, not a defect in the builders themselves.",
    "Workbook formulas are compared as text; cached formula results are not evaluated.",
    "Workbook charts are compared by type, position and the cell ranges they plot, not by colour or font; images in "
    "a workbook (an export has none) are not compared; the rules inside data validations and conditional formats "
    "are not compared (only how many there are). The document's embedded images are compared by alt text and "
    "content hash.",
    "Document comments, footnotes, text boxes, themes and file properties are not compared.",
    "Run it from the directory the export was run from: a draft image path is resolved against the working directory.",
)


def _is_number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _values_equal(expected, actual):
    if _is_number(expected) and _is_number(actual):
        return math.isclose(expected, actual, rel_tol=NUMERIC_TOLERANCE, abs_tol=NUMERIC_TOLERANCE)
    return type(expected) is type(actual) and expected == actual


def _finding(artifact, location, kind, expected, actual):
    return {"artifact": artifact, "location": location, "kind": kind, "expected": expected, "actual": actual}


def _load_workbook(path):
    try:
        return openpyxl.load_workbook(path)
    except Exception as exc:  # openpyxl raises a mix of zip, XML and key errors for a damaged file
        raise ValueError(f"cannot read workbook {path}: {exc}") from exc


def _load_document(path):
    try:
        return docx.Document(path)
    except Exception as exc:  # python-docx raises a mix of zip, XML and key errors for a damaged file
        raise ValueError(f"cannot read document {path}: {exc}") from exc


def _color(color):
    """A colour as a comparable list: its kind (rgb, theme, indexed, auto), that kind's value, and its tint."""
    if color is None:
        return None
    kind = color.type
    value = {"rgb": color.rgb, "theme": color.theme, "indexed": color.indexed, "auto": color.auto}.get(kind)
    return [kind, value, color.tint or 0]


def _border(cell):
    sides = {}
    for name in ("left", "right", "top", "bottom"):
        side = getattr(cell.border, name)
        sides[name] = [side.style, _color(side.color)] if side is not None else None
    return sides


def _fill(cell):
    fill = cell.fill
    return [fill.fill_type, _color(fill.fgColor), _color(fill.bgColor)] if fill.fill_type else None


# Every cell property that is compared besides its value: the finding's `kind` and how to read it from a cell.
CELL_PROPERTIES = (
    ("number_format", lambda cell: cell.number_format),
    ("bold", lambda cell: bool(cell.font.bold)),
    ("italic", lambda cell: bool(cell.font.italic)),
    ("underline", lambda cell: cell.font.underline),
    ("strike", lambda cell: bool(cell.font.strike)),
    ("font_name", lambda cell: cell.font.name),
    ("font_size", lambda cell: cell.font.sz),
    ("font_color", lambda cell: _color(cell.font.color)),
    ("fill", _fill),
    ("border", _border),
    ("alignment", lambda cell: [cell.alignment.horizontal, cell.alignment.vertical, bool(cell.alignment.wrap_text)]),
)


def compare_workbooks(expected_path, actual_path):
    """Findings for every difference between two workbooks' sheets, cells, formats, visibility and layout."""
    expected, actual = _load_workbook(expected_path), _load_workbook(actual_path)
    findings = []
    if expected.sheetnames != actual.sheetnames:
        findings.append(_finding("workbook", "sheet names", "sheets", expected.sheetnames, actual.sheetnames))
    want_names = sorted((name, value.attr_text) for name, value in expected.defined_names.items())
    have_names = sorted((name, value.attr_text) for name, value in actual.defined_names.items())
    if want_names != have_names:
        findings.append(_finding("workbook", "defined names", "defined_names", want_names, have_names))
    for name in expected.sheetnames:
        if name not in actual.sheetnames:
            continue
        findings.extend(_compare_sheets(name, expected[name], actual[name]))
    return findings


def _compare_sheets(name, expected, actual):
    findings = []
    rows = max(expected.max_row, actual.max_row)
    columns = max(expected.max_column, actual.max_column)
    if rows * columns > MAX_COMPARED_CELLS:
        raise ValueError(
            f"worksheet {name!r} uses {rows} rows by {columns} columns, more than the {MAX_COMPARED_CELLS} positions "
            "a read-back compares; an export is not that large, so the file was edited")
    for row in range(1, rows + 1):
        for column in range(1, columns + 1):
            want, have = expected.cell(row=row, column=column), actual.cell(row=row, column=column)
            location = f"{name}!{want.coordinate}"
            if not _values_equal(want.value, have.value):
                findings.append(_finding("workbook", location, "value", want.value, have.value))
            for kind, read in CELL_PROPERTIES:
                want_property, have_property = read(want), read(have)
                if not _values_equal(want_property, have_property):
                    findings.append(_finding("workbook", location, kind, want_property, have_property))
    findings.extend(_compare_sheet_layout(name, expected, actual))
    return findings


def _reference(part):
    """The cell range a chart part (a series' values, categories or name) points at, or None."""
    if part is None:
        return None
    for source in (getattr(part, "numRef", None), getattr(part, "strRef", None)):
        if source is not None:
            return source.f
    return None


def _chart_signature(chart):
    anchor = chart.anchor._from
    series = [[_reference(s.tx), _reference(s.val), _reference(s.cat)] for s in chart.series]
    return [chart.tagname, anchor.row, anchor.col, getattr(chart, "grouping", None), getattr(chart, "type", None),
            series]


def _sheet_charts(sheet):
    return sorted((_chart_signature(chart) for chart in sheet._charts), key=lambda signature: signature[1:3])


def _compare_sheet_layout(name, expected, actual):
    findings = []

    def compare(location, kind, want, have):
        if not _values_equal(want, have):
            findings.append(_finding("workbook", f"{name}!{location}", kind, want, have))

    compare("sheet", "sheet_state", expected.sheet_state, actual.sheet_state)
    compare("sheet", "protection", bool(expected.protection.sheet), bool(actual.protection.sheet))
    for index in sorted(set(expected.row_dimensions) | set(actual.row_dimensions)):
        want, have = expected.row_dimensions[index], actual.row_dimensions[index]
        compare(f"row {index}", "row_hidden", bool(want.hidden), bool(have.hidden))
        compare(f"row {index}", "row_height", want.height, have.height)
    for letter in sorted(set(expected.column_dimensions) | set(actual.column_dimensions)):
        want, have = expected.column_dimensions[letter], actual.column_dimensions[letter]
        compare(f"column {letter}", "column_width", want.width, have.width)
        compare(f"column {letter}", "column_hidden", bool(want.hidden), bool(have.hidden))
    compare("merged cells", "merged_cells", sorted(str(r) for r in expected.merged_cells.ranges),
            sorted(str(r) for r in actual.merged_cells.ranges))
    compare("freeze panes", "freeze_panes", expected.freeze_panes, actual.freeze_panes)
    compare("data validations", "data_validations", len(expected.data_validations.dataValidation),
            len(actual.data_validations.dataValidation))
    compare("conditional formats", "conditional_formatting", len(expected.conditional_formatting),
            len(actual.conditional_formatting))
    compare("charts", "charts", _sheet_charts(expected), _sheet_charts(actual))
    compare("defined names", "sheet_defined_names", sorted((n, v.attr_text) for n, v in expected.defined_names.items()),
            sorted((n, v.attr_text) for n, v in actual.defined_names.items()))
    return findings


def _text_value(value):
    return None if value is None else str(value)


def _points(length):
    return None if length is None else length.pt


def _run_signature(run):
    font = run.font
    color = font.color
    rgb = theme = None
    if color is not None and color.type is not None:
        rgb, theme = _text_value(color.rgb), _text_value(color.theme_color)
    return ["run", run.text, bool(run.bold), bool(run.italic), _text_value(font.underline), bool(font.strike),
            font.name, _points(font.size), rgb, theme, _text_value(font.highlight_color),
            _text_value(font.superscript), _text_value(font.subscript), bool(font.all_caps), bool(font.small_caps),
            bool(font.hidden)]


def _paragraph_block(part, paragraph):
    parts = []
    for item in paragraph.iter_inner_content():
        if isinstance(item, Hyperlink):
            parts.append(["link", item.url, [_run_signature(run) for run in item.runs]])
        else:
            parts.append(_run_signature(item))
    images = []
    for blip in paragraph._p.xpath(".//a:blip/@r:embed"):
        related = part.related_parts.get(blip)
        images.append(hashlib.sha256(related.blob).hexdigest() if related is not None else None)
    alt_texts = list(paragraph._p.xpath(".//wp:docPr/@descr"))
    extents = [[extent.get("cx"), extent.get("cy")] for extent in paragraph._p.xpath(".//wp:extent")]
    layout = paragraph.paragraph_format
    return {"type": "paragraph", "style": paragraph.style.name, "parts": parts, "image_hashes": images,
            "image_alt_text": alt_texts, "image_extents": extents,
            "layout": [_text_value(paragraph.alignment), _points(layout.left_indent), _points(layout.space_before),
                       _points(layout.space_after), _text_value(layout.line_spacing)]}


# The direct table and cell formatting that changes how a table looks: shading, borders, widths, vertical alignment
# and spanning. Read from the XML because python-docx does not expose most of it.
TABLE_LAYOUT_XPATH = ("./w:tblPr/w:tblW | ./w:tblPr/w:jc | ./w:tblPr/w:shd | ./w:tblPr/w:tblLayout | "
                      "./w:tblPr/w:tblBorders/* | ./w:tblGrid/w:gridCol")
CELL_LAYOUT_XPATH = ("./w:tcPr/w:tcW | ./w:tcPr/w:shd | ./w:tcPr/w:vAlign | ./w:tcPr/w:gridSpan | "
                     "./w:tcPr/w:vMerge | ./w:tcPr/w:tcBorders/*")


def _layout_properties(element, xpath):
    return [[node.tag.rsplit("}", 1)[-1], sorted((key.rsplit("}", 1)[-1], value) for key, value in node.attrib.items())]
            for node in element.xpath(xpath)]


def _table_block(part, table):
    return {"type": "table", "style": table.style.name if table.style is not None else None,
            "layout": _layout_properties(table._tbl, TABLE_LAYOUT_XPATH),
            "rows": [[{"layout": _layout_properties(cell._tc, CELL_LAYOUT_XPATH),
                       "paragraphs": [_paragraph_block(part, paragraph) for paragraph in cell.paragraphs]}
                      for cell in row.cells] for row in table.rows]}


def _blocks(element, parent, part):
    """The paragraphs and tables directly under `element` (the body, a header or a footer), in order."""
    blocks = []
    for child in element.iterchildren():
        tag = child.tag.rsplit("}", 1)[-1]
        if tag == "p":
            blocks.append(_paragraph_block(part, Paragraph(child, parent)))
        elif tag == "tbl":
            blocks.append(_table_block(part, Table(child, parent)))
    return blocks


def _story_signature(story):
    """A header or footer: whether it is inherited from the previous section, and otherwise its own content."""
    if story.is_linked_to_previous:
        return {"linked": True}
    return {"linked": False, "blocks": _blocks(story._element, story, story.part)}


def _section_block(section):
    return {"type": "section", "page": [_points(section.page_width), _points(section.page_height),
                                        _text_value(section.orientation)],
            "margins": [_points(section.left_margin), _points(section.right_margin), _points(section.top_margin),
                        _points(section.bottom_margin)],
            "different_first_page": bool(section.different_first_page_header_footer),
            "header": _story_signature(section.header), "footer": _story_signature(section.footer),
            "first_page_header": _story_signature(section.first_page_header),
            "first_page_footer": _story_signature(section.first_page_footer),
            "even_page_header": _story_signature(section.even_page_header),
            "even_page_footer": _story_signature(section.even_page_footer)}


def _style_signature(style):
    font, layout = style.font, getattr(style, "paragraph_format", None)
    color = font.color
    rgb = theme = None
    if color is not None and color.type is not None:
        rgb, theme = _text_value(color.rgb), _text_value(color.theme_color)
    signature = [style.name, _text_value(style.type), style.base_style.name if style.base_style is not None else None,
                 font.name, _points(font.size), font.bold, font.italic, _text_value(font.underline), rgb, theme]
    if layout is not None:
        signature += [_text_value(layout.alignment), _points(layout.left_indent), _points(layout.space_before),
                      _points(layout.space_after), _text_value(layout.line_spacing)]
    return signature


def _used_style_names(value, found):
    """Every paragraph and table style name that appears in the compared blocks and sections."""
    if isinstance(value, dict):
        if isinstance(value.get("style"), str):
            found.add(value["style"])
        for nested in value.values():
            _used_style_names(nested, found)
    elif isinstance(value, list):
        for nested in value:
            _used_style_names(nested, found)
    return found


def _style_definitions(document, names):
    return {style.name: _style_signature(style) for style in document.styles if style.name in names}


def _document_sections(document):
    return [_section_block(section) for section in document.sections]


def _document_blocks(document):
    return _blocks(document.element.body, document, document.part)


def compare_documents(expected_path, actual_path):
    """Findings for every difference between two documents' body blocks, in order."""
    expected_document, actual_document = _load_document(expected_path), _load_document(actual_path)
    expected, actual = _document_blocks(expected_document), _document_blocks(actual_document)
    findings = []
    if len(expected) != len(actual):
        findings.append(_finding("document", "block count", "blocks", len(expected), len(actual)))
    for index in range(min(len(expected), len(actual))):
        want, have = expected[index], actual[index]
        if want != have:
            findings.append(_finding("document", f"block {index + 1}", want["type"], want, have))
    want_sections, have_sections = _document_sections(expected_document), _document_sections(actual_document)
    # A style used by only one of the two is already a difference in the blocks above; here, a style both use must
    # still be defined alike (a heading restyled to one-point white text changes no paragraph, only its style).
    shared = (_used_style_names([expected, want_sections], set()) & _used_style_names([actual, have_sections], set()))
    want_styles, have_styles = _style_definitions(expected_document, shared), _style_definitions(actual_document, shared)
    for name in sorted(shared):
        if want_styles.get(name) != have_styles.get(name):
            findings.append(_finding("document", f"style {name}", "style", want_styles.get(name),
                                     have_styles.get(name)))
    if len(want_sections) != len(have_sections):
        findings.append(_finding("document", "section count", "sections", len(want_sections), len(have_sections)))
    for index in range(min(len(want_sections), len(have_sections))):
        if want_sections[index] != have_sections[index]:
            findings.append(_finding("document", f"section {index + 1}", "section", want_sections[index],
                                     have_sections[index]))
    return findings


def _approved_draft(state, deal_folder, base_dir):
    """The approved draft's path: repository-relative, a regular file inside the deal's own dated folder."""
    recorded = state.get("approved_draft_path")
    if not isinstance(recorded, str) or not recorded.strip():
        raise StateError(
            "state.json records no approved_draft_path, so the document cannot be checked; "
            "/assemble records it when it exports")
    # Absolute on either platform's rules: a state.json written on Windows can be read on Linux and the reverse.
    if (PureWindowsPath(recorded).is_absolute() or PurePosixPath(recorded).is_absolute()
            or ".." in recorded.replace("\\", "/").split("/")):
        raise StateError(f"approved_draft_path {recorded!r} must be a relative path inside the deal's dated folder")
    path = os.path.join(base_dir, recorded) if base_dir else recorded
    folder_real = os.path.realpath(deal_folder)
    path_real = os.path.realpath(path)
    if os.path.commonpath([folder_real, path_real]) != folder_real:
        raise StateError(f"approved_draft_path {recorded!r} is not inside the deal's dated folder {deal_folder}")
    if not os.path.isfile(path):
        raise StateError(f"the approved draft {recorded!r} named by state.json does not exist")
    return path


def _require_file(path, what):
    if not os.path.isfile(path):
        raise StateError(f"the {what} {path} does not exist; nothing to compare")


def verify_deal(company, proposal, date_str=None, base_dir=None):
    """Compare this deal's exported workbook and document with what its record regenerates. Returns the report."""
    company = sanitize_path_component(company, "company")
    proposal = sanitize_path_component(proposal, "proposal")
    if date_str is not None:
        validate_iso_date_str(date_str, field_name="--date-str")
        if not os.path.isfile(state_path(company, proposal, date_str=date_str, base_dir=base_dir)):
            raise StateError(f"no state.json in the dated folder {proposal}_{date_str}; nothing to compare")
    else:
        found = find_deal(company, proposal, base_dir=base_dir)
        if not found["record_found"]:
            raise StateError(f"no existing state.json for company {company!r} and proposal {proposal!r}")
        date_str = found["date"]
    state = read_state(company, proposal, date_str=date_str, base_dir=base_dir, keys=STATE_KEYS_READ) or {}
    validate_state(state, keys=("group_basis",),
                   path=state_path(company, proposal, date_str=date_str, base_dir=base_dir))
    folder = os.path.dirname(state_path(company, proposal, date_str=date_str, base_dir=base_dir))
    workbook_path = os.path.join(folder, f"{company}_{proposal}_Spreading.xlsx")
    document_path = os.path.join(folder, f"{company}_{proposal}_CAM.docx")
    _require_file(workbook_path, "workbook")
    _require_file(document_path, "document")
    draft_path = _approved_draft(state, folder, base_dir)
    with open(draft_path, encoding="utf-8") as handle:
        draft_markdown = handle.read()

    with tempfile.TemporaryDirectory(prefix="export_readback_") as scratch:
        expected_workbook = os.path.join(scratch, "expected.xlsx")
        expected_document = os.path.join(scratch, "expected.docx")
        export_to_xlsx(company, expected_workbook, **workbook_inputs_from_state(state))
        export_to_docx(draft_markdown, expected_document)
        workbook_findings = compare_workbooks(expected_workbook, workbook_path)
        document_findings = compare_documents(expected_document, document_path)

    findings = workbook_findings + document_findings
    return {
        "status": "match" if not findings else "mismatch",
        "selected_folder": folder,
        "artifacts": {
            "workbook": {"path": workbook_path, "status": "match" if not workbook_findings else "mismatch",
                         "mismatch_count": len(workbook_findings)},
            "document": {"path": document_path, "status": "match" if not document_findings else "mismatch",
                         "mismatch_count": len(document_findings)},
            "approved_draft": draft_path,
        },
        "mismatch_count": len(findings),
        "findings": findings[:MAX_FINDINGS],
        "truncated": len(findings) > MAX_FINDINGS,
        "limits": list(LIMITS),
    }


def main(argv=None):
    import argparse

    parser = argparse.ArgumentParser(
        description="Compare a deal's exported workbook (.xlsx) and CAM document (.docx) with what its state.json "
                    "and approved draft regenerate, and report every difference. Read-only for the deal; has no "
                    "Anthropic dependency. A change detector for edits after export, not proof the exporter is right."
    )
    parser.add_argument("--company", required=True)
    parser.add_argument("--proposal", required=True)
    parser.add_argument(
        "--date-str", default=None,
        help="YYYY-MM-DD suffix of the deal's dated folder. Defaults to the deal's newest dated folder that has a "
             "state.json.")
    args = parser.parse_args(argv)
    try:
        report = verify_deal(args.company, args.proposal, date_str=args.date_str)
    except (OSError, ValueError) as exc:
        sys.exit(f"error: {exc}")
    print(json.dumps(report, indent=2, default=str))
    return 0 if report["status"] == "match" else 1


if __name__ == "__main__":
    from textio import configure_stdio
    configure_stdio()
    sys.exit(main())
