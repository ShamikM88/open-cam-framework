def _evaluate(ws, col, row, memo):
    key = (col, row)
    if key in memo:
        return memo[key]
    raw = ws[f"{col}{row}"].value
    if raw is None:
        result = 0
    elif isinstance(raw, (int, float)):
        result = raw
    elif isinstance(raw, str) and raw.startswith("="):
        result = _eval_expr(ws, raw[1:], memo)
    else:
        raise AssertionError(f"Unexpected non-numeric, non-formula value at {col}{row}: {raw!r}")
    memo[key] = result
    return result


def _eval_expr(ws, expr, memo):
    m = re.fullmatch(r"SUM\(([A-Z]+)(\d+):([A-Z]+)(\d+)\)", expr)
    if m:
        col1, r1, col2, r2 = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
        assert col1 == col2, f"Unsupported multi-column SUM range: {expr}"
        return sum(_evaluate(ws, col1, r, memo) for r in range(r1, r2 + 1))

    m = re.fullmatch(r'IFERROR\((.+),"([^"]*)"\)', expr)
    if m:
        inner, fallback = m.group(1), m.group(2)
        try:
            return _eval_expr(ws, inner, memo)
        except (ZeroDivisionError, TypeError):      # TypeError: arithmetic on an "N/A" text cell (Excel's #VALUE!)
            return fallback

    m = re.fullmatch(r"IF\((.+)\)", expr)
    if m:
        condition, when_true, when_false = _split_top_level_args(m.group(1))
        chosen = when_true if _eval_arith(ws, condition, memo) else when_false
        text = re.fullmatch(r'"([^"]*)"', chosen)
        return text.group(1) if text else _eval_arith(ws, chosen, memo)

    return _eval_arith(ws, expr, memo)


def _split_top_level_args(arguments):
    """'(a)>0,(b)/(c),"N/A"' -> three strings, splitting only on commas outside parentheses and quotes."""
    parts, depth, in_quotes, current = [], 0, False, ""
    for char in arguments:
        if char == '"':
            in_quotes = not in_quotes
        elif not in_quotes and char == "(":
            depth += 1
        elif not in_quotes and char == ")":
            depth -= 1
        if char == "," and depth == 0 and not in_quotes:
            parts.append(current)
            current = ""
        else:
            current += char
    parts.append(current)
    assert len(parts) == 3, f"IF() needs exactly three arguments: {arguments!r}"
    return parts


def _eval_arith(ws, expr, memo):
    # COUNT over bare cell refs (the workbook's formulas never nest it): counts numeric cells
    # exactly like Excel -- blank (None) and text cells are not numbers and never count. Substituted
    # before the cell-ref pass below, which would otherwise read the label-column cells COUNT guards.
    def count_of(match):
        refs = match.group(1).split(",")
        return str(sum(1 for ref in refs
                      if isinstance(ws[ref.strip()].value, (int, float))
                      and not isinstance(ws[ref.strip()].value, bool)))

    expr = re.sub(r"COUNT\(([^()]+)\)", count_of, expr)

    def repl(match):
        col, row = match.group(1), int(match.group(2))
        return repr(_evaluate(ws, col, row, memo))

    substituted = CELL_REF_RE.sub(repl, expr)
    # Formulas are generated by spreading_builder.py itself (not user input),
    # and every cell reference has already been replaced with a numeric
    # literal, so eval() here only ever runs arithmetic on numbers.
    return eval(substituted, {"__builtins__": {}}, {})


